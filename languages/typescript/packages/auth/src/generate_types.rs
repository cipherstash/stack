//! Generator binary that produces `index.d.ts` by combining Specta's structured
//! type information with field-level doc comments extracted from Rust source via
//! `syn`. This produces:
//!
//! - `export class DeviceCodeResult` with `readonly` properties and method
//!   signatures (with JSDoc for `pollForToken()` and `openInBrowser()`)
//! - `export interface TokenResult` with per-field JSDoc
//!
//! Run via: `cargo run --bin generate-types`

use std::collections::HashMap;
use std::fs;
use std::path::Path;

use stack_auth::{PendingDeviceCode, Token};
use regex::Regex;
use specta::ts;
use specta::{DefOpts, NamedType, TypeDefs};

fn main() {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let crate_src = manifest_dir.join("../src");

    // expires_in is u64 in Rust but always a safe integer in practice, so
    // export it as `number` rather than `bigint`.
    let config = ts::ExportConfiguration::default().bigint(ts::BigIntExportBehavior::Number);

    // Parse Rust source files to extract field-level doc comments.
    let device_code_src = fs::read_to_string(crate_src.join("device_code/mod.rs"))
        .expect("Failed to read device_code/mod.rs");
    let lib_src = fs::read_to_string(crate_src.join("lib.rs")).expect("Failed to read lib.rs");

    let device_code_docs = extract_field_docs(&device_code_src, "PendingDeviceCode");
    let token_docs = extract_field_docs(&lib_src, "Token");

    // Build rich TypeScript declarations from Specta metadata + syn doc comments.
    let device_code_class = build_class::<PendingDeviceCode>(&device_code_docs, &config);
    let token_iface = build_interface::<Token>(&token_docs, &config);

    let mut out = String::new();

    out.push_str("// This file is auto-generated by `generate-types`. Do not edit by hand.\n");
    out.push_str("// Regenerate with: npm run generate-types\n\n");

    // -----------------------------------------------------------------------
    // Specta-generated type definitions (from the cts-auth crate)
    // -----------------------------------------------------------------------

    out.push_str(&device_code_class);
    out.push_str("\n\n");
    out.push_str(&token_iface);
    out.push_str("\n\n");

    // -----------------------------------------------------------------------
    // Hand-written error types (better TSDoc control per variant)
    // -----------------------------------------------------------------------

    out.push_str(
        r#"/**
 * Machine-readable error codes attached to {@link AuthError}.
 *
 * - `"REQUEST_ERROR"` — The HTTP request to the auth server failed (network error, timeout, etc.).
 * - `"ACCESS_DENIED"` — The user explicitly denied authorization.
 * - `"EXPIRED_TOKEN"` — The device code expired before the user authorized.
 * - `"INVALID_GRANT"` — The grant type is invalid or the device code was already used.
 * - `"INVALID_CLIENT"` — The `clientId` is not recognized by the auth server.
 * - `"INVALID_URL"` — A URL argument could not be parsed.
 * - `"INVALID_REGION"` — The `region` string does not match a known CipherStash region.
 * - `"SERVER_ERROR"` — The auth server returned an unexpected error.
 */
export type AuthErrorCode =
  | "REQUEST_ERROR"
  | "ACCESS_DENIED"
  | "EXPIRED_TOKEN"
  | "INVALID_GRANT"
  | "INVALID_CLIENT"
  | "INVALID_URL"
  | "INVALID_REGION"
  | "SERVER_ERROR";

/**
 * Error thrown by all functions in this module.
 *
 * Extends the built-in `Error` with a machine-readable {@link AuthErrorCode}
 * so callers can branch on `err.code` without parsing the message string.
 */
export interface AuthError extends Error {
  code: AuthErrorCode;
}
"#,
    );

    out.push('\n');

    // -----------------------------------------------------------------------
    // Function declarations with TSDoc
    // -----------------------------------------------------------------------

    out.push_str(
        r#"/**
 * Begin the OAuth 2.0 Device Authorization flow.
 *
 * Contacts the CipherStash auth server for the given region and returns a
 * {@link DeviceCodeResult} with a user code, verification URL, and methods
 * to complete the authorization flow.
 *
 * @param region - CipherStash region identifier (e.g. `"ap-southeast-2"`).
 * @param clientId - OAuth client ID issued by CipherStash.
 * @returns A promise that resolves with the device code result.
 * @throws {AuthError} `INVALID_REGION` — the region string is not recognized.
 * @throws {AuthError} `INVALID_CLIENT` — the client ID is not recognized.
 * @throws {AuthError} `REQUEST_ERROR` — the HTTP request to the auth server failed.
 * @throws {AuthError} `SERVER_ERROR` — the auth server returned an unexpected error.
 *
 * @example
 * ```ts
 * import { beginDeviceCodeFlow } from "@cipherstash/cts-auth";
 *
 * // 1. Start the flow
 * const result = await beginDeviceCodeFlow("ap-southeast-2", MY_CLIENT_ID);
 * console.log(`Enter code ${result.userCode} at ${result.verificationUri}`);
 *
 * // 2. Optionally open the browser for the user
 * result.openInBrowser();
 *
 * // 3. Poll until the user authorizes (or the code expires)
 * const token = await result.pollForToken();
 * console.log(`Access token: ${token.accessToken}`);
 * ```
 */
export function beginDeviceCodeFlow(
  region: string,
  clientId: string,
): Promise<DeviceCodeResult>;

/**
 * Variant of {@link beginDeviceCodeFlow} that targets a custom auth server URL.
 *
 * Intended for **testing only** — requires the crate to be built with the
 * `test-utils` Cargo feature.
 *
 * @param region - CipherStash region identifier (e.g. `"ap-southeast-2"`).
 * @param clientId - OAuth client ID issued by CipherStash.
 * @param baseUrl - Base URL of the auth server to use instead of the default.
 * @returns A promise that resolves with the device code result.
 * @throws {AuthError} `INVALID_REGION` — the region string is not recognized.
 * @throws {AuthError} `INVALID_URL` — the base URL could not be parsed.
 * @throws {AuthError} `INVALID_CLIENT` — the client ID is not recognized.
 * @throws {AuthError} `REQUEST_ERROR` — the HTTP request to the auth server failed.
 * @throws {AuthError} `SERVER_ERROR` — the auth server returned an unexpected error.
 */
export function beginDeviceCodeFlowWithBaseUrl(
  region: string,
  clientId: string,
  baseUrl: string,
): Promise<DeviceCodeResult>;
"#,
    );

    // -----------------------------------------------------------------------
    // Write to index.d.ts in the package root
    // -----------------------------------------------------------------------

    let dest = manifest_dir.join("index.d.ts");

    fs::write(&dest, &out).unwrap_or_else(|e| panic!("Failed to write {}: {e}", dest.display()));

    println!("Wrote {}", dest.display());
}

