#!/bin/sh
# copy.sh copies sqlc-gen-go's internal package and the packages under it into
# this folder, from the version the tool line in sqlc-gen-stash's go.mod pins,
# and rewrites their import paths. Every file in this folder except build.go
# and copy.sh comes from it, and go generate runs it.
set -eu

module=github.com/sqlc-dev/sqlc-gen-go
src=$(go list -f '{{.Dir}}' "$module/internal")
version=$(go list -m -f '{{.Version}}' "$module")

find . -mindepth 1 -maxdepth 1 ! -name build.go ! -name copy.sh -exec rm -rf {} +
cp -R "$src"/. .
cp "$src/../LICENSE" LICENSE
chmod -R u+w .
# sqlc-gen-go's own tests and their fixtures stay behind.
find . -name '*_test.go' -delete
rm -rf endtoend

find . -name '*.go' ! -name build.go | while read -r f; do
	{
		printf '// Code generated by copy.sh from %s %s. DO NOT EDIT.\n\n' "$module/internal" "$version"
		sed "s#\"$module/internal#\"github.com/cipherstash/stack/languages/golang/cmd/sqlc-gen-stash/internal/golang#" "$f"
	} >"$f.tmp"
	mv "$f.tmp" "$f"
done
# The new import path sorts differently.
gofmt -w .
