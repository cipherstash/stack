//! The Python `stackencrypt._eql` module emitter: renders `eql_domains::CATALOG`
//! to the committed `languages/python/python/stackencrypt/_eql.py` — one
//! marker class per EQL type, each carrying the catalog row's columns as
//! class attributes, and a `TYPES` tuple listing them in catalog order. The
//! spec (#1341, "Markers (generated)") fixes the ten attributes and puts the
//! emitter here, beside the Go one.
//!
//! The rows are [`crate::targets`]', the same the Go `Types` table and the
//! Rust `TARGETS` table are rendered from, so Python and Go cannot disagree
//! about a type; `tests/py_eql_parity.rs` compares the two outputs attribute
//! by attribute. A marker is named by the catalog name as it is (`TextEq`,
//! `Json`): Python has no initialism rule to apply.
//!
//! `__all__` lists the producible markers only. The package re-exports the
//! module with `from stackencrypt._eql import *`, so a marker the engine
//! cannot produce yet is in the module but not importable from the package.
//!
//! Generate-to-file like the Go module: `eql-codegen py-eql` writes the file,
//! `mise run types:check` diffs it, and `tests/py_eql_parity.rs` asserts the
//! committed file is what the catalog renders.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::targets::{rows, Row};

/// The generated file, relative to the EQL subtree root (`repo_root()`):
/// the Python workspace lives beside `packages/` in the monorepo.
pub const PY_EQL_PATH: &str = "../../languages/python/python/stackencrypt/_eql.py";

/// The first line of the generated file, in the form Go uses and editors
/// recognise.
pub const PY_GENERATED_MARKER: &str =
    "# Code generated by eql-codegen from the eql-domains catalog. DO NOT EDIT.";

/// A Python string literal. Catalog text is printable, so only the quote
/// and the backslash need escaping; anything else is refused rather than
/// written in an escape Python would read differently.
fn py_str(s: &str) -> String {
    assert!(
        !s.chars().any(char::is_control),
        "catalog text with a control character: {s:?}"
    );
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// A Python string literal, or `None` for an absent value.
fn py_opt(s: Option<&str>) -> String {
    s.map_or_else(|| "None".to_owned(), py_str)
}

/// A Python tuple of strings: `()`, `("eq",)` or `("eq", "ore")`.
fn py_tuple(items: &[&str]) -> String {
    match items {
        [] => "()".to_owned(),
        [one] => format!("({},)", py_str(one)),
        _ => {
            let quoted: Vec<String> = items.iter().map(|s| py_str(s)).collect();
            format!("({})", quoted.join(", "))
        }
    }
}

/// The first docstring line and the status line, in the Go emitter's words.
fn docstring(row: &Row) -> String {
    let indexes = if row.indexes.is_empty() {
        "no index".to_owned()
    } else {
        format!(
            "the {} index{}",
            row.indexes.join(" and "),
            if row.indexes.len() > 1 { "es" } else { "" }
        )
    };
    let status = match (row.reason, row.plaintext) {
        (None, Some(kind)) => {
            let article = if kind.starts_with(['a', 'e', 'i', 'o', 'u']) {
                "an"
            } else {
                "a"
            };
            format!("The engine produces it from {article} {kind}.")
        }
        (None, None) => "The engine produces it.".to_owned(),
        (Some(reason), _) => format!("The engine cannot produce it yet: {reason}."),
    };
    let text = format!(
        "The EQL type stored in {domain}: the {family} family with {indexes}.\n\n    {status}\n    ",
        domain = row.sql_domain,
        family = row.family,
    );
    assert!(!text.contains("\"\"\""), "catalog text ends the docstring");
    format!("\"\"\"{}\"\"\"", text.replace('\\', "\\\\"))
}

fn class(out: &mut String, row: &Row) {
    let (query, query_sql_domain) = match &row.query {
        Some((query, domain)) => (Some(query.as_str()), Some(domain.as_str())),
        None => (None, None),
    };
    let _ = write!(
        out,
        "\n\nclass {name}(Marker):\n    {doc}\n\n    \
         name = {name_lit}\n    \
         family = {family}\n    \
         suffix = {suffix}\n    \
         plaintext = {plaintext}\n    \
         sql_domain = {sql_domain}\n    \
         indexes = {indexes}\n    \
         query = {query}\n    \
         query_sql_domain = {query_sql_domain}\n    \
         producible = {producible}\n    \
         reason = {reason}\n",
        name = row.name,
        doc = docstring(row),
        name_lit = py_str(&row.name),
        family = py_str(row.family),
        suffix = py_str(&row.suffix),
        plaintext = py_opt(row.plaintext),
        sql_domain = py_str(&row.sql_domain),
        indexes = py_tuple(&row.indexes),
        query = py_opt(query),
        query_sql_domain = py_opt(query_sql_domain),
        producible = if row.reason.is_none() {
            "True"
        } else {
            "False"
        },
        reason = py_opt(row.reason),
    );
}

/// Render the Python source of `_eql.py`.
pub fn render_py_eql() -> String {
    let rows = rows();
    let mut out = String::new();
    let _ = writeln!(
        out,
        "{PY_GENERATED_MARKER}\n\
         \"\"\"The EQL types as stash markers: one class per catalog row, in catalog order.\n\
         \n\
         Generated from the same catalog rows as the Go package encrypt/eql. ``__all__``\n\
         lists the markers the engine produces today, which the package re-exports.\n\
         \"\"\"\n\
         \n\
         from stackencrypt._markers import Marker\n\
         \n\
         __all__ = ["
    );
    for row in rows.iter().filter(|row| row.reason.is_none()) {
        let _ = writeln!(out, "    {},", py_str(&row.name));
    }
    out.push_str("]\n");
    for row in &rows {
        class(&mut out, row);
    }
    out.push_str("\n\nTYPES = (\n");
    for row in &rows {
        let _ = writeln!(out, "    {},", row.name);
    }
    out.push_str(")\n");
    out
}

/// Write `_eql.py` under `out_root` (the EQL subtree root).
pub fn generate_py_eql(out_root: &Path) -> std::io::Result<PathBuf> {
    let path = out_root.join(PY_EQL_PATH);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, render_py_eql())?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strings_escape_the_quote_and_the_backslash() {
        assert_eq!(py_str(r#"a "b" \c"#), r#""a \"b\" \\c""#);
    }

    #[test]
    fn tuples_have_python_syntax_for_every_length() {
        assert_eq!(py_tuple(&[]), "()");
        assert_eq!(py_tuple(&["eq"]), r#"("eq",)"#);
        assert_eq!(py_tuple(&["eq", "ore"]), r#"("eq", "ore")"#);
    }

    #[test]
    fn every_row_is_one_class_and_one_entry_in_types() {
        let rendered = render_py_eql();
        let count = rows().len();
        assert_eq!(rendered.matches("(Marker):\n").count(), count);
        let types = rendered.split("TYPES = (\n").nth(1).expect("a TYPES tuple");
        assert_eq!(types.lines().filter(|l| l.ends_with(',')).count(), count);
    }
}
