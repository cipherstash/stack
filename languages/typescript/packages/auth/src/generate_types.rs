// Helpers
// ---------------------------------------------------------------------------

/// Parse a Rust source file with `syn` and extract doc comments from the fields
/// of the given struct. Returns a map from field name (snake_case) to the
/// trimmed doc comment text.
fn extract_field_docs(source: &str, struct_name: &str) -> HashMap<String, String> {
    let file = syn::parse_file(source).expect("Failed to parse Rust source");
    let mut docs = HashMap::new();

    for item in &file.items {
        let syn::Item::Struct(s) = item else {
            continue;
        };
        if s.ident != struct_name {
            continue;
        }

        let syn::Fields::Named(fields) = &s.fields else {
            continue;
        };
        for field in &fields.named {
            let Some(ident) = &field.ident else {
                continue;
            };

            let doc_lines: Vec<String> = field
                .attrs
                .iter()
                .filter_map(|attr| {
                    if !attr.path().is_ident("doc") {
                        return None;
                    }
                    let syn::Meta::NameValue(nv) = &attr.meta else {
                        return None;
                    };
                    let syn::Expr::Lit(lit) = &nv.value else {
                        return None;
                    };
                    let syn::Lit::Str(s) = &lit.lit else {
                        return None;
                    };
                    Some(s.value())
                })
                .collect();

            if !doc_lines.is_empty() {
                let combined = doc_lines
                    .iter()
                    .map(|l| l.strip_prefix(' ').unwrap_or(l))
                    .collect::<Vec<_>>()
                    .join("\n");
                docs.insert(ident.to_string(), combined.trim().to_string());
            }
        }
        break; // Found the struct, no need to continue.
    }

    docs
}

/// Convert Rust intra-doc links (`` [`text`](Rust::path) ``) to TSDoc
/// `{@link text}` references.
fn convert_rust_doc_links(doc: &str) -> String {
    let re = Regex::new(r"\[`([^`]+)`\]\([^)]+\)").expect("invalid regex");
    re.replace_all(doc, "{@link $1}").to_string()
}

/// Convert `camelCase` to `snake_case`.
fn to_snake_case(s: &str) -> String {
    let mut result = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            result.push('_');
        }
        result.extend(c.to_lowercase());
    }
    result
}

/// Build a multi-line TypeScript `export class` declaration from Specta
/// metadata and syn-extracted field doc comments. Properties are `readonly`
/// and class methods (`pollForToken`, `openInBrowser`) are appended.
fn build_class<T: NamedType>(
    field_docs: &HashMap<String, String>,
    config: &ts::ExportConfiguration,
) -> String {
    let mut type_defs = TypeDefs::default();
    let named = T::definition_named_data_type(DefOpts {
        parent_inline: false,
        type_map: &mut type_defs,
    })
    .expect("Failed to get named data type");

    let ts_name = named.name;

    let mut out = String::new();

    // Struct-level JSDoc from Specta's comments (originally `///` on the struct).
    if !named.comments.is_empty() {
        out.push_str("/**\n");
        for comment in named.comments {
            let line = comment.strip_prefix(' ').unwrap_or(comment);
            if line.is_empty() {
                out.push_str(" *\n");
            } else {
                let converted = convert_rust_doc_links(line);
                out.push_str(&format!(" * {converted}\n"));
            }
        }
        out.push_str(" */\n");
    }

    out.push_str(&format!("export class {ts_name} {{\n"));

    // Extract object fields.
    let fields = match &named.item {
        specta::NamedDataTypeItem::Object(obj) => &obj.fields,
        _ => panic!("{ts_name} is not an object type"),
    };

    for field in fields {
        let key = field.key;
        let snake_key = to_snake_case(key);

        if let Some(doc) = field_docs.get(&snake_key) {
            let converted = convert_rust_doc_links(doc);
            out.push_str(&format!("  /** {converted} */\n"));
        }

        let ts_type = ts::datatype(config, &field.ty)
            .unwrap_or_else(|e| panic!("Failed to convert field {key}: {e}"));

        out.push_str(&format!("  readonly {key}: {ts_type};\n"));
    }

    // Class methods
    out.push_str(
        r#"
  /**
   * Poll the auth server until the user completes authorization.
   *
   * **Consumes** the internal handle — it cannot be reused after this call.
   * If you need to open the browser, call {@link openInBrowser} *before*
   * `pollForToken`.
   *
   * @returns A promise that resolves with the access token details.
   * @throws {AuthError} `EXPIRED_TOKEN` — the device code expired before the user authorized.
   * @throws {AuthError} `ACCESS_DENIED` — the user denied authorization.
   * @throws {AuthError} `INVALID_GRANT` — the grant type is invalid or the code was already used.
   * @throws {AuthError} `REQUEST_ERROR` — the HTTP request to the auth server failed.
   * @throws {AuthError} `SERVER_ERROR` — the auth server returned an unexpected error.
   */
  pollForToken(): Promise<TokenResult>;

  /**
   * Open the verification URI in the user's default browser.
   *
   * Does **not** consume the handle — you can still call {@link pollForToken}
   * afterwards.
   *
   * @returns `true` if the browser was launched successfully, `false` otherwise.
   */
  openInBrowser(): boolean;
"#,
    );

    out.push('}');
    out
}

/// Build a multi-line TypeScript `export interface` declaration from Specta
/// metadata and syn-extracted field doc comments.
fn build_interface<T: NamedType>(
    field_docs: &HashMap<String, String>,
    config: &ts::ExportConfiguration,
) -> String {
    let mut type_defs = TypeDefs::default();
    let named = T::definition_named_data_type(DefOpts {
        parent_inline: false,
        type_map: &mut type_defs,
    })
    .expect("Failed to get named data type");

    let ts_name = named.name;

    let mut out = String::new();

    // Struct-level JSDoc from Specta's comments (originally `///` on the struct).
    if !named.comments.is_empty() {
        out.push_str("/**\n");
        for comment in named.comments {
            let line = comment.strip_prefix(' ').unwrap_or(comment);
            if line.is_empty() {
                out.push_str(" *\n");
            } else {
                let converted = convert_rust_doc_links(line);
                out.push_str(&format!(" * {converted}\n"));
            }
        }
        out.push_str(" */\n");
    }

    out.push_str(&format!("export interface {ts_name} {{\n"));

    // Extract object fields.
    let fields = match &named.item {
        specta::NamedDataTypeItem::Object(obj) => &obj.fields,
        _ => panic!("{ts_name} is not an object type"),
    };

    for field in fields {
        let key = field.key;
        let snake_key = to_snake_case(key);

        if let Some(doc) = field_docs.get(&snake_key) {
            let converted = convert_rust_doc_links(doc);
            out.push_str(&format!("  /** {converted} */\n"));
        }

        let ts_type = ts::datatype(config, &field.ty)
            .unwrap_or_else(|e| panic!("Failed to convert field {key}: {e}"));

        let optional = if field.optional { "?" } else { "" };
        out.push_str(&format!("  {key}{optional}: {ts_type};\n"));
    }

    out.push('}');
    out
}
