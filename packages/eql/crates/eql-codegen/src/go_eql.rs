//! The Go `encrypt/eql` package emitter: renders `eql_domains::CATALOG` to
//! the committed `languages/golang/encrypt/eql/eql_gen.go` in the Go module
//! — one Go type per EQL type, holding the value as the JSON bytes its
//! column stores, the query types that match them, and a `Types` table a
//! generator or a program can consult. The plan
//! (`docs/plans/2026-10-04-plan-builder.md`, "EQL types") puts the package
//! here: "eql-codegen writes the package encrypt/eql from the EQL catalog".
//!
//! The rows are [`crate::targets`]', the same the Rust `TARGETS` table is
//! rendered from, so the Go table and the engine's `se_targets` cannot
//! disagree about a type. The Go names follow the catalog names with one
//! rule: the JSON family's begin with `JSON` (`Json` is `JSON`), as Go
//! spells initialisms; `stashgen` applies the same rule when it writes a
//! field's type.
//!
//! Generate-to-file like the Rust bindings: `eql-codegen go-eql` writes the
//! file, `mise run types:check` diffs it, and `tests/go_eql_parity.rs`
//! asserts the committed file is what the catalog renders. The output is
//! gofmt-clean by construction — one-line table rows and block-bodied
//! methods, the two shapes gofmt does not realign — and the Go CI's
//! `gofmt -l` is the check that it stayed so.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::targets::{rows, Row};

/// The generated file, relative to the EQL subtree root (`repo_root()`):
/// the Go module lives beside `packages/` in the monorepo.
pub const GO_EQL_PATH: &str = "../../languages/golang/encrypt/eql/eql_gen.go";

/// The header every generated Go file carries: the `Code generated ... DO
/// NOT EDIT.` form `go vet` and editors recognise.
pub const GO_GENERATED_MARKER: &str =
    "// Code generated by eql-codegen from the eql-domains catalog. DO NOT EDIT.";

/// The Go type name of a catalog name: the same, save that the word
/// `Json` is spelled `JSON`, as Go spells initialisms: `Json` is `JSON`,
/// `JsonSearchQuery` is `JSONSearchQuery`. `Json` is a word where
/// it ends the name or the next letter starts another (upper case).
pub fn go_name(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut rest = name;
    while let Some(at) = rest.find("Json") {
        let after = &rest[at + 4..];
        out.push_str(&rest[..at]);
        if after.chars().next().is_none_or(char::is_uppercase) {
            out.push_str("JSON");
        } else {
            out.push_str("Json");
        }
        rest = after;
    }
    out.push_str(rest);
    out
}

/// A Go string literal.
fn quote(s: &str) -> String {
    format!("{s:?}")
}

/// A Go `[]string` literal, `nil` when empty.
fn strings(items: &[&str]) -> String {
    if items.is_empty() {
        return "nil".to_owned();
    }
    let quoted: Vec<String> = items.iter().map(|s| quote(s)).collect();
    format!("[]string{{{}}}", quoted.join(", "))
}

fn table_row(row: &Row) -> String {
    let (query, query_domain) = row
        .query
        .as_ref()
        .map(|(q, d)| (q.as_str(), d.as_str()))
        .unwrap_or_default();
    format!(
        "\t{{Name: {}, GoName: {}, Family: {}, Suffix: {}, Plaintext: {}, SQLDomain: {}, \
         Indexes: {}, Query: {}, QuerySQLDomain: {}, Producible: {}, Reason: {}}},\n",
        quote(&row.name),
        quote(&go_name(&row.name)),
        quote(row.family),
        quote(&row.suffix),
        quote(row.plaintext.unwrap_or_default()),
        quote(&row.sql_domain),
        strings(&row.indexes),
        quote(query),
        quote(query_domain),
        row.reason.is_none(),
        quote(row.reason.unwrap_or_default()),
    )
}

/// The four methods every EQL type and query type carries, block-bodied so
/// gofmt leaves them as written.
fn methods(out: &mut String, go: &str, domain: &str) {
    let _ = write!(
        out,
        "\n// Value is the EQL value as the driver takes it: the JSON text, or NULL when empty.\n\
         func (v {go}) Value() (driver.Value, error) {{\n\treturn value(v)\n}}\n\
         \n// Scan reads a {domain} column.\n\
         func (v *{go}) Scan(src any) error {{\n\treturn scan((*[]byte)(v), src, {q})\n}}\n\
         \n// MarshalJSON is the EQL value as the JSON it is, or null when empty.\n\
         func (v {go}) MarshalJSON() ([]byte, error) {{\n\treturn marshal(v, {q})\n}}\n\
         \n// UnmarshalJSON reads the EQL value from JSON, as it is.\n\
         func (v *{go}) UnmarshalJSON(b []byte) error {{\n\treturn unmarshal((*[]byte)(v), b)\n}}\n",
        q = quote(go),
    );
}

/// Render the Go source of `eql_gen.go`.
pub fn render_go_eql() -> String {
    let rows = rows();
    let mut out = String::new();
    let _ = writeln!(
        out,
        "{GO_GENERATED_MARKER}\n\npackage eql\n\nimport \"database/sql/driver\"\n"
    );
    out.push_str(
        "// Types is every EQL type the catalog has, in catalog order: what the\n\
         // engine's se_targets export lists, as Go. Producible says whether the\n\
         // engine produces the type today; stashgen refuses encrypt_into for one\n\
         // it does not, with the Reason.\n\
         var Types = []Type{\n",
    );
    for row in &rows {
        out.push_str(&table_row(row));
    }
    out.push_str("}\n");
    for row in &rows {
        let go = go_name(&row.name);
        let indexes = if row.indexes.is_empty() {
            "no index".to_owned()
        } else {
            format!(
                "the {} index{}",
                row.indexes.join(" and "),
                if row.indexes.len() > 1 { "es" } else { "" }
            )
        };
        let status = match (row.reason, row.plaintext) {
            (None, Some(kind)) => {
                // The Go kinds are read as words: "an int32", "a float64".
                let article = if kind.starts_with(['a', 'e', 'i', 'o', 'u']) {
                    "an"
                } else {
                    "a"
                };
                format!("The engine produces it from {article} {kind}.")
            }
            (None, None) => "The engine produces it.".to_owned(),
            (Some(reason), _) => format!("The engine cannot produce it yet: {reason}."),
        };
        let _ = write!(
            out,
            "\n// {go} is the EQL type stored in {domain}: the {family} family with {indexes}.\n// {status}\ntype {go} []byte\n",
            domain = row.sql_domain,
            family = row.family,
        );
        methods(&mut out, &go, &row.sql_domain);
        if let Some((query, query_domain)) = &row.query {
            let query_go = go_name(query);
            let _ = write!(
                out,
                "\n// {query_go} is the query value for {go}: the operand {query_domain} takes.\ntype {query_go} []byte\n",
            );
            methods(&mut out, &query_go, query_domain);
        }
    }
    document_types(&mut out);
    range_types(&mut out);
    out
}

/// The document families' types beside their stored type and its needle:
/// the ordering operand and the entry the SQL returns (`->`, the walks),
/// each the JSON bytes it is in SQL, like every other type. Not in the
/// `Types` table, which lists stored types.
fn document_types(out: &mut String) {
    use eql_domains::DocumentRole;
    for family in eql_domains::DOCUMENT_FAMILIES {
        for domain in family.domains {
            let what = match domain.role {
                DocumentRole::Stored | DocumentRole::Query => continue,
                DocumentRole::LeafQuery => {
                    "ordering operand at a path, compared with an entry `->` extracts"
                }
                DocumentRole::Entry => {
                    "entry: one node of a document, as `->` and the walks return it"
                }
            };
            let go = go_name(domain.name);
            let _ = write!(
                out,
                "\n// {go} is the {family} family's {what}: the value {sql} holds.\ntype {go} []byte\n",
                family = family.name,
                sql = domain.sql_domain,
            );
            methods(out, &go, domain.sql_domain);
        }
    }
}

/// The range query types: one per family and ordering term, the operand of
/// `eql_v4.between` (ADR-0009 decision 7), so a `Between` term binds as one
/// parameter. Each holds the JSON `{"v", "i", "lo", "hi"}` value as bytes,
/// like every other query type. Not in the `Types` table, which lists
/// stored types; no stored type is producible yet for a range to query.
fn range_types(out: &mut String) {
    for family in eql_domains::families_with_scalar_domains() {
        for term in family.range_terms() {
            let go = go_name(&family.range_struct_ident(term));
            let domain = crate::range::range_sql_domain(family, term);
            let index = crate::targets::index_key(term);
            let columns: Vec<String> = family
                .range_columns(term)
                .iter()
                .map(|d| go_name(&d.rust_struct_name(family.name)))
                .collect();
            let _ = write!(
                out,
                "\n// {go} is a range query value over the {index} index of the {family} family: \
                 both bounds of one BETWEEN,\n// included, as the one operand {domain} takes in \
                 eql_v4.between. It ranges over {columns}.\ntype {go} []byte\n",
                family = family.name,
                columns = columns.join(", "),
            );
            methods(out, &go, &domain);
        }
    }
}

/// Write `eql_gen.go` under `out_root` (the EQL subtree root, or the
/// override `EQL_CODEGEN_OUT_ROOT`). Returns the path written.
pub fn generate_go_eql(out_root: &Path) -> std::io::Result<PathBuf> {
    let path = out_root.join(GO_EQL_PATH);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, render_go_eql())?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn go_names_follow_the_catalog_save_the_json_family() {
        assert_eq!(go_name("TextEq"), "TextEq");
        assert_eq!(go_name("TextEqQuery"), "TextEqQuery");
        assert_eq!(go_name("Json"), "JSON");
        assert_eq!(go_name("SteVecDocument"), "SteVecDocument");
        assert_eq!(go_name("JsonSearch"), "JSONSearch");
        assert_eq!(go_name("JsonSearchLeafQuery"), "JSONSearchLeafQuery");
        assert_eq!(go_name("JsonEntry"), "JSONEntry");
        assert_eq!(go_name("Jsonify"), "Jsonify", "a word, not a prefix");
        assert_eq!(
            go_name("Jsonécrit"),
            "Jsonécrit",
            "the next character, not byte"
        );
        assert_eq!(go_name("JsonÉcrit"), "JSONÉcrit");
    }

    #[test]
    fn the_document_family_has_its_go_types() {
        let out = render_go_eql();
        for go in [
            "JSONSearch",
            "JSONSearchQuery",
            "JSONSearchLeafQuery",
            "JSONEntry",
        ] {
            assert_eq!(
                out.matches(&format!("\ntype {go} []byte\n")).count(),
                1,
                "{go}"
            );
        }
        assert!(out.contains(
            "Name: \"JsonSearch\", GoName: \"JSONSearch\", Family: \"json_tree\", Suffix: \"\", \
             Plaintext: \"json\", SQLDomain: \"public.eql_v4_json_search\", Indexes: []string{\"json\"}, \
             Query: \"JsonSearchQuery\", QuerySQLDomain: \"eql_v4.query_json\", Producible: true"
        ));
    }

    #[test]
    fn the_package_has_one_type_per_row_and_one_query_type_per_twin() {
        let out = render_go_eql();
        assert!(out.starts_with(GO_GENERATED_MARKER));
        assert!(out.contains("\npackage eql\n"));
        for row in rows() {
            let go = go_name(&row.name);
            assert_eq!(
                out.matches(&format!("\ntype {go} []byte\n")).count(),
                1,
                "{go}"
            );
            assert!(
                out.contains(&format!("Name: {:?}, GoName: {go:?}", row.name)),
                "{go} in the table"
            );
            if let Some((query, _)) = &row.query {
                let query_go = go_name(query);
                assert_eq!(
                    out.matches(&format!("\ntype {query_go} []byte\n")).count(),
                    1,
                    "{query_go}"
                );
            }
        }
        // No type is declared twice, and the SteVec document, EQL v3 only,
        // has no v4 type.
        assert_eq!(out.matches("\ntype JSON []byte\n").count(), 1);
        assert!(!out.contains("SteVec"));
        // TextEq is producible and says so; Json is not and says why.
        assert!(out.contains("// TextEq is the EQL type stored in public.eql_v4_text_eq"));
        assert!(out.contains("Producible: true, Reason: \"\""));
        assert!(
            out.contains("Name: \"Json\"")
                && out.contains("a JSON value seals as a tree of leaves")
        );
        // Every table row is one line: the shape gofmt leaves alone.
        for line in out.lines().filter(|l| l.starts_with("\t{Name: ")) {
            assert!(line.ends_with("},"), "{line}");
        }
    }

    #[test]
    fn the_package_has_one_range_type_per_family_and_ordering_term() {
        let out = render_go_eql();
        let mut count = 0;
        for family in eql_domains::families_with_scalar_domains() {
            for term in family.range_terms() {
                let go = family.range_struct_ident(term);
                assert_eq!(
                    out.matches(&format!("\ntype {go} []byte\n")).count(),
                    1,
                    "{go}"
                );
                assert!(out.contains(&format!("func (v {go}) Value() (driver.Value, error)")));
                count += 1;
            }
        }
        assert_eq!(count, 18, "nine ordered families, ORE and OPE each");
        assert!(out.contains(
            "// IntegerRangeOreQuery is a range query value over the ore_block index of the integer family: \
             both bounds of one BETWEEN,\n// included, as the one operand eql_v4.query_integer_range_ore \
             takes in eql_v4.between. It ranges over IntegerOrdOre.\n"
        ));
        assert!(out.contains("It ranges over TextOrd, TextOrdOpe, TextSearch.\n"));
        // Range types are query types, not stored ones: not in the table.
        assert!(!out.contains("Name: \"IntegerRangeOreQuery\""));
    }

    #[test]
    fn the_plaintext_kind_takes_the_article_it_is_read_with() {
        let out = render_go_eql();
        assert!(out.contains("The engine produces it from an int32."));
        assert!(out.contains("The engine produces it from a float64."));
        assert!(!out.contains("from a int"), "a int32 or a int64");
    }

    #[test]
    fn rendering_is_deterministic() {
        assert_eq!(render_go_eql(), render_go_eql());
    }
}
